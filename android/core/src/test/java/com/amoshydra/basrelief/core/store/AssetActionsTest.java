package com.amoshydra.basrelief.core.store;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

import org.junit.Test;

/**
 * The sheet's one shared asset row: which secondary actions a row may offer once
 * the primary build lives in the 3D-build dialog's tabs.
 *
 * <p>The traps are the ones the two removed rows carried. Delete belongs to a cloud
 * that is <b>here</b> and to no run that owns the row; Replace belongs to a still
 * depth <b>file</b> and to nothing else — an embedded map has depth and no file, an
 * unread window has no answer at all, and a row with no map is the fix line's
 * "Choose a map" rather than this row's Replace. A clip's track offers neither, and
 * its regeneration runs the video graph instead, because the Relief tab refuses a
 * track by {@link BuildTab}'s own rule and would otherwise strand the action.
 *
 * <p>It also pins that the ranking is {@link BuildTab}'s, not a second one: a run in
 * flight offers nothing and a failure outranks the asset it left behind, in this row
 * exactly as in the tabs — the two answers are the tabs' own, so there is nothing to
 * drift.
 */
public class AssetActionsTest {

    /** A separate depth file: the one depth a still row may replace. */
    private static DepthSource.Answer depthFile() {
        return DepthSource.resolve(true, false);
    }

    /** A depth chunk inside the image: depth, and no file to act on. */
    private static DepthSource.Answer embedded() {
        return DepthSource.resolve(false, true);
    }

    /** A clip whose tracks are here: its depth is a track, not a file. */
    private static DepthSource.Answer track() {
        return DepthSource.resolve(VideoSource.resolve(true, Boolean.TRUE), true, null);
    }

    /** Neither depth nor a window: the row has no map at all. */
    private static DepthSource.Answer none() {
        return DepthSource.resolve(false, false);
    }

    private static AssetActions.Answer resolve(BuildTab.Answer cloud, BuildTab.Answer relief,
                                               DepthSource.Answer depth, boolean clip) {
        return AssetActions.resolve(cloud, relief, depth, clip);
    }

    // ------------------------------------------------------------------ delete

    /** A cloud that is here, with no run owning the row, is deletable. */
    @Test
    public void aBuiltCloudIsDeletable() {
        AssetActions.Answer a = resolve(BuildTab.forSplat(true, false, false),
                BuildTab.forRelief(false, true, false, false), none(), false);
        assertTrue(a.canDeleteCloud());
    }

    /** No cloud is no Delete — the row has nothing to remove. */
    @Test
    public void noCloudIsNotDeletable() {
        AssetActions.Answer a = resolve(BuildTab.forSplat(false, false, false),
                BuildTab.forRelief(false, true, false, false), none(), false);
        assertFalse(a.canDeleteCloud());
    }

    /**
     * A run in flight offers nothing, and a failure outranks the asset it left.
     *
     * <p>This is {@link BuildTab#forSplat}'s ranking read through this row, and it
     * is why the shared row does not re-decide run state: a build in flight owns the
     * row, and a failed build is the thing the user has to act on rather than the
     * old cloud behind it.
     */
    @Test
    public void aCloudRunOffersNoDelete() {
        DepthSource.Answer noDepth = none();
        BuildTab.Answer noRelief = BuildTab.forRelief(false, true, false, false);
        assertFalse(resolve(BuildTab.forSplat(true, true, false), noRelief, noDepth, false)
                .canDeleteCloud());
        assertFalse(resolve(BuildTab.forSplat(true, false, true), noRelief, noDepth, false)
                .canDeleteCloud());
        // Even when a run is in flight over a failure: the run is the current truth.
        assertFalse(resolve(BuildTab.forSplat(true, true, true), noRelief, noDepth, false)
                .canDeleteCloud());
    }

    // ----------------------------------------------------------------- replace

    /** A still depth file is replaced, never regenerated by this row. */
    @Test
    public void aStillDepthFileIsReplaced() {
        AssetActions.Answer a = resolve(BuildTab.forSplat(false, false, false),
                BuildTab.forRelief(true, true, false, false), depthFile(), false);
        assertEquals(AssetActions.DepthAction.REPLACE, a.depthAction());
    }

    /** A row with no map offers no Replace: adding one is the fix line's action. */
    @Test
    public void aRowWithNoDepthOffersNoReplace() {
        BuildTab.Answer relief = BuildTab.forRelief(false, true, false, false);
        assertEquals(AssetActions.DepthAction.NONE, resolve(BuildTab.forSplat(false, false, false),
                relief, none(), false).depthAction());
        assertEquals(AssetActions.DepthAction.NONE, resolve(BuildTab.forSplat(false, false, false),
                relief, DepthSource.UNKNOWN, false).depthAction());
    }

    /** An embedded map has depth and no file, so it offers nothing at all. */
    @Test
    public void anEmbeddedMapOffersNothing() {
        // The Relief tab is BUILT for an embedded map (it has depth) with no action.
        BuildTab.Answer relief = BuildTab.forRelief(true, false, false, false);
        assertEquals(BuildTab.State.BUILT, relief.state());
        AssetActions.Answer a = resolve(BuildTab.forSplat(false, false, false),
                relief, embedded(), false);
        assertEquals(AssetActions.DepthAction.NONE, a.depthAction());
        assertTrue(a.isNone());
    }

    /** A depth run in flight, or a failed one, offers nothing on this row either. */
    @Test
    public void aDepthRunOffersNothing() {
        assertEquals(AssetActions.DepthAction.NONE, resolve(BuildTab.forSplat(false, false, false),
                BuildTab.forRelief(true, true, true, false), depthFile(), false).depthAction());
        assertEquals(AssetActions.DepthAction.NONE, resolve(BuildTab.forSplat(false, false, false),
                BuildTab.forRelief(true, true, false, true), depthFile(), false).depthAction());
    }

    // -------------------------------------------------------------- clip track

    /**
     * A clip's track is regenerated here, because the Relief tab refuses it.
     *
     * <p>{@link BuildTab#forRelief} answers BUILT with no action for a track, so the
     * video-graph regeneration has no tab to live in. Removing the bottom block
     * without this would have stranded it.
     */
    @Test
    public void aClipTrackIsRegenerated() {
        // The caller resolves a clip against the video job: a depth, no action, no
        // run -- which is BUILT, exactly as a track is for the tab.
        AssetActions.Answer a = resolve(BuildTab.forSplat(false, false, false),
                BuildTab.forRelief(true, false, false, false), track(), true);
        assertEquals(AssetActions.DepthAction.REGENERATE, a.depthAction());
    }

    /**
     * A clip's regeneration is a run too, so it is offered only when nothing owns
     * the row — the same rule the still path follows.
     */
    @Test
    public void aClipRunOffersNoRegenerate() {
        assertEquals(AssetActions.DepthAction.NONE, resolve(BuildTab.forSplat(false, false, false),
                BuildTab.forRelief(true, false, true, false), track(), true).depthAction());
        assertEquals(AssetActions.DepthAction.NONE, resolve(BuildTab.forSplat(false, false, false),
                BuildTab.forRelief(true, false, false, true), track(), true).depthAction());
    }

    // ------------------------------------------------------------------- shape

    /** Both assets present offers both actions, and is therefore not hidden. */
    @Test
    public void bothAssetsOfferBothActions() {
        AssetActions.Answer a = resolve(BuildTab.forSplat(true, false, false),
                BuildTab.forRelief(true, true, false, false), depthFile(), false);
        assertTrue(a.canDeleteCloud());
        assertEquals(AssetActions.DepthAction.REPLACE, a.depthAction());
        assertFalse(a.isNone());
    }

    /**
     * A row with neither asset is hidden, which is the whole of "a control that
     * cannot change anything is a lie".
     */
    @Test
    public void aRowWithNothingToOfferIsHidden() {
        AssetActions.Answer a = resolve(BuildTab.forSplat(false, false, false),
                BuildTab.forRelief(false, true, false, false), none(), false);
        assertTrue(a.isNone());
        assertFalse(a.canDeleteCloud());
        assertEquals(AssetActions.DepthAction.NONE, a.depthAction());
    }

    /** An unresolved answer claims nothing, the same "a window claims nothing" rule. */
    @Test
    public void anUnresolvedRowIsHidden() {
        assertTrue(AssetActions.resolve(null, null, null, false).isNone());
    }
}
