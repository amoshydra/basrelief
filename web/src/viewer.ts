/**
 * The viewer's ONE dispatch point.
 *
 * A card is the studio's row, one platform over: **a photograph (or a dropped
 * cloud) plus optionally a depth map plus optionally a splat cloud.** The
 * Renderer segment picks which asset is drawn, the asset row states the selected
 * mode's asset and offers its build, and the rest of the sheet is the studio's
 * vocabulary over the same camera the app uses.
 *
 * The renderers are named modules (`relief.ts`, `cloud.ts`) behind this switch,
 * and a photograph is a plain `<img>` — three cases, no renderer interface.
 *
 * **Android owns the design.** The camera is `CameraModel`'s (`camera.ts`) and
 * `SplatCamera`'s (`splat.ts`): tap sets the orbit centre by ray-casting into the
 * medium, one-finger drag pans, two fingers pan and pinch (Pan Z, the app's
 * dolly), Zoom is a crop of the same camera, and the crosshair marks the pivot
 * from the frame that was drawn. Origin, Pan, Pan Z and Zoom are LIVE rows.
 */

/**
 * A splat cloud held by a card.
 *
 * A dropped `.splat` keeps its `File` (its bytes are read on open, because a card
 * should not read a 13 MB file to show a count); a cloud built on this page is
 * written to the library store by the gallery, and this session's copy carries
 * the bytes until it has been.
 */
export interface CloudAsset {
  /** The dropped file, when the cloud arrived as one. */
  file: File | null;
  /** The generated bytes, when this page built it. */
  bytes: Uint8Array | null;
  /** `basrelief_<tag>.splat`, or the dropped file's name. */
  name: string;
  /** `focal / height` from the sidecar, or 0 for "no lens". */
  lens: number;
  /** The sidecar that stated the lens, or null. */
  lensFrom: string | null;
  /** Whole 32-byte records. */
  splats: number;
}

export interface OpenableItem {
  name: string;
  /** The dropped file itself; a cloud's bytes are read from here. */
  file: File;
  /** Object URL for the colour image; owned by the gallery item, not revoked here. */
  url: string;
  state: MediaState;
  depth: DephSuccess | null;
  size: number;
  width: number;
  height: number;
  /** `focal / height` from the cloud's sidecar, or 0 when nothing claimed a lens. */
  lens: number;
  /** The sidecar that stated it, for the line that says which camera this is. */
  lensFrom: string | null;
  /** A cloud built on this page for this card, if one was. */
  cloud: CloudAsset | null;
  /**
   * Whether the ROW names a cloud, whether or not its bytes have been read.
   *
   * The bytes are loaded on first open now, so `cloud` can be null for a row that
   * plainly has one; `Scene3D`'s question is about the row, not about what this
   * session has fetched.
   */
  hasCloud?: boolean;
  /**
   * A build's state, reported to the gallery.
   *
   * A run outlives this viewer: the sheet can be dismissed and the generation
   * keeps going. The tile is then the only place its progress can be seen, so the
   * state has to leave this closure.
   */
  onBuild?: (state: { phase: string | null; failed: string | null } | null) => void;
  /**
   * The cloud's bytes, fetched on first open: a card states its count from the
   * file's length, so nothing reads the records until the viewer needs them.
   */
  loadCloudFile?: () => Promise<File | null>;
  /**
   * The row's own render values for this surface, from `library.json`.
   *
   * The studio's values belong to a photograph and a screen, not to the tab, so
   * the viewer starts from the row rather than from the defaults — which is what
   * makes a tuned look survive a refresh.
   */
  settings: SurfaceSettings;
  /** Which asset the row asks for (`RenderMode`). */
  mode: Mode;
  /**
   * Called when a control commits: on release, on a nudge, on a mode switch and
   * on Reset. The gallery owns the row, so it is the one that writes it.
   *
   * Deliberately not called per input frame: a page that stored at the drag's
   * frame rate would rewrite its library sixty times for one gesture, and the
   * app's own rule is preview while dragging, commit on release.
   */
  onSettings?: (settings: SurfaceSettings, mode: Mode) => void;
  /**
   * Called when this page packs a new depth map into the photo. The gallery owns
   * the card, so it replaces the dropped file with the packed one and repaints —
   * the generated relief is still there when the viewer is reopened, without any
   * storage and without a second copy of the classifier.
   */
  onGenerated?: (file: File, depth: DephSuccess, width: number, height: number) => void;
  /** Called when a cloud is built or deleted; null means deleted. */
  onCloud?: (cloud: CloudAsset | null) => void;
  /**
   * The library, as the sheet's filmstrip.
   *
   * Studio sheet content, directly under the grip and above the fix line and the
   * scroll — the app's `Gallery.installStrip(panel, 1)`, and it fades with the
   * sheet because it IS the sheet. Absent or empty hides it (a lone `.splat` this
   * session is not in the library, so there is nothing to strip).
   */
  strip?: readonly StripEntry[];
  /** A strip tile was chosen: the gallery opens that row instead of this one. */
  onPick?: (id: string) => void;
  /**
   * `sheet_pos` / `sheet_open_pos`: where the studio sheet last rested, as the app
   * stores it. `null` is a fresh install, which opens at the peek.
   */
  sheetPos?: { fraction: number | null; open: number | null };
  /** The sheet came to rest: the app's `onSheetResting`, written to `prefs.json`. */
  onSheetResting?: (fraction: number, collapsed: boolean) => void;
}

/** What an open viewer hands back, so a strip tile can swap one row for another. */
export interface ViewerHandle {
  close(): void;
}

