  /**
   * The studio's fix line: the selected mode's state and the up-to-two actions it
   * offers, outside the scroll, in a dashed box. A state with no button is still
   * drawn (a run owns the row), because a sentence is not a control.
   *
   * It is the phone's `buildFixLine` — 14px side margins, 11px corners, an
   * 11/11/11/12 pad — and it lives outside the scroll for the phone's reason: it is
   * the one thing that must be readable at the launch peek, when the foot of the
   * sheet is still below the fold. Inside the scroll it would be the first thing to
   * scroll away, which is exactly when a condition needs reading.
   *
   * The ranking is `BuildTab`'s: a run in flight offers nothing, and a failure
   * outranks the asset it left behind. A Relief row never carries a run — the build
   * dialog's status line is its signal — while a cloud build has no second line, so
   * its phase and failure live here.
   */
  function appendFixLine(panel: Sheet): void {
    const row = document.createElement('div');
    row.className = 'sheet-asset-row';
    // The asset state and its actions live in the scroll, below the Renderer
    // segment, as asked: map creation and regeneration belong to the mode that
    // will use the map. The fix line is left hidden.
    panel.body.append(row);

    // A status line for a chosen map's own progress, inside the box so it cannot
    // stack a second one and so it is readable at any height.
    const statusEl = note('');
    statusEl.hidden = true;
    statusEl.setAttribute('role', 'status');
    panel.body.append(statusEl);

    const render = (): void => {
      row.replaceChildren();
      const stateEl = document.createElement('span');
      stateEl.className = 'sheet-asset-state';
      const actions: AssetAction[] = [];

      if (mode === 'relief') {
        if (build?.phase) {
          // A run owns the row: asking for a second one over the first is the
          // control `BuildTab` refuses to offer.
          stateEl.textContent = build.phase;
        } else if (build?.failed) {
          // A failure outranks the asset it left behind, and keeps the server's
          // own words until the user acts on it.
          stateEl.textContent = `Build failed — ${build.failed}`;
          if (hasColour()) {
            actions.push({ label: 'Regenerate', onClick: () => openBuild('relief') });
          }
        } else if (depth || colourState.kind === 'relief') {
          // A depth map this card has -- separate file or embedded in the PNG.
          // The earlier test asked only `depth`, which is null for an embedded
          // map, so a packed PNG read "No depth map yet" while the renderer drew
          // it: the sheet contradicted the picture.
          stateEl.textContent = 'Has a depth map';
          actions.push(
            { label: 'Choose a map', onClick: () => void chooseDepthMap(statusEl) },
            { label: 'Generate', onClick: () => openBuild('relief') },
          );
        } else {
          stateEl.textContent = 'No depth map yet';
          actions.push(
            { label: 'Choose a map', onClick: () => void chooseDepthMap(statusEl) },
            { label: 'Generate', onClick: () => openBuild('relief') },
          );
        }
      } else {
        const cloudNow = currentCloud();
        const building = build?.phase ?? null;
        if (building) {
          stateEl.textContent = building;
        } else if (build?.failed) {
          stateEl.textContent = `Build failed — ${build.failed}`;
          if (hasColour()) {
            actions.push({ label: 'Regenerate', onClick: () => openBuild('splat') });
          }
        } else if (cloudNow) {
          stateEl.textContent = `${formatSplatCount(cloudNow.splats)} · SHARP`;
          if (hasColour()) {
            actions.push({ label: 'Rebuild', onClick: () => openBuild('splat') });
          }
          actions.push({ label: 'Delete', onClick: () => deleteCloud() });
        } else {
          stateEl.textContent = 'no cloud yet — make one?';
          if (hasColour()) {
            actions.push({ label: 'Make one', onClick: () => openBuild('splat') });
          }
        }
      }

      row.append(stateEl);
      for (const action of actions) {
        const button = document.createElement('button');
        button.type = 'button';
        button.className = 'sheet-asset-btn';
        button.textContent = action.label;
        button.addEventListener('click', action.onClick);
        row.append(button);
      }
      // The dashed edge recolours for a condition that needs the user, because the
      // border is what the eye lands on: a dashed line saying "failed" in white
      // reads as an informational line.
      // The fix line is hidden now that the row lives in the scroll, so the
      // attention state has to live where the row does -- otherwise the dashed
      // border that says "something needs you" is drawn on an element nobody
      // sees, which is dead code that looks alive.
      row.classList.toggle('is-attention', build?.failed ? true : !has3D());
      syncPill();
    };

    render();
    assetRowRender = render;
  }

