  async function applyDepthFile(file: File, status: HTMLElement): Promise<void> {
    status.hidden = false;
    status.classList.remove('sheet-note--warn');
    status.textContent = 'Reading the depth map…';
    try {
      const target = await colourDimensions();
      const depth = await grayFromFile(file, target.width, target.height);
      const colour = await colourPngBytes(item.file);
      const packed = packPng(colour.bytes, depth);
      if (!packed.ok) throw new Error(packed.detail);
      if (closed) return;
      if (generatedUrl) URL.revokeObjectURL(generatedUrl);
      generatedUrl = URL.createObjectURL(new Blob([new Uint8Array(packed.png)], { type: 'image/png' }));
      const packedFile = new File(
        [new Uint8Array(packed.png)],
        packedFileName(item.file.name),
        { type: 'image/png' },
      );
      item.onGenerated?.(packedFile, depth, target.width, target.height);
      // THIS page's copy of the card, so a later mode switch still finds the map.
      thisCardDepth(depth, colour.reencoded, packed.png);
      mode = 'relief';
      await mountRelief(depth, {
        imageUrl: generatedUrl,
        packed: packed.png,
        reencoded: colour.reencoded,
      });
    } catch (err) {
      if (closed) return;
      status.hidden = false;
      status.classList.add('sheet-note--warn');
      status.textContent = `Could not use that depth map: ${
        err instanceof Error ? err.message : 'the file could not be read'
      }`;
    }
  }

