  /**
   * The studio's gesture set, on one pointer map.
   *
   * **Tap** sets the orbit centre by ray-casting into the medium (the cloud) or
   * unprojecting to the plane under the finger (the relief) — not a screen
   * fraction, which would drift with Pan and with a cloud's Depth. **One-finger
   * drag** pans. **Two fingers** pan by their midpoint and pinch the camera
   * distance (Pan Z), which is `MainActivity`'s own mapping: pinch drives the
   * dolly, and the FOV row is the separate crop.
   *
   * Every gesture writes the session's settings and PUSHES the rows, because a
   * gesture owns the renderer's values and a row that re-read storage would be a
   * staler source of truth. Nothing persists: there is nothing to commit on
   * release, which is the one place this page is simpler than the app.
   */
  function installGestures(
    target: HTMLElement,
    teardownList: Array<() => void>,
    view: ReliefView | CloudView,
  ): void {
    const pointers = new Map<number, { x: number; y: number }>();
    const SLOP = 6;
    let downX = 0;
    let downY = 0;
    let downAt = 0;
    let moved = false;
    let pinchStartDist = 0;
    let pinchStartPanZ = 1;
    let lastMidX = 0;
    let lastMidY = 0;
    /** Set by any gesture that moved a stored value; committed on the last lift. */
    let framingTouched = false;

    const local = (event: PointerEvent): { x: number; y: number; rect: DOMRect } => {
      const rect = target.getBoundingClientRect();
      return { x: event.clientX - rect.left, y: event.clientY - rect.top, rect };
    };

    const midpoint = (): { x: number; y: number } => {
      let x = 0;
      let y = 0;
      for (const p of pointers.values()) {
        x += p.x;
        y += p.y;
      }
      const n = Math.max(1, pointers.size);
      return { x: x / n, y: y / n };
    };

    const distance = (): number => {
      const [a, b] = [...pointers.values()];
      return a && b ? Math.hypot(a.x - b.x, a.y - b.y) : 0;
    };

    const panBy = (dx: number, dy: number): void => {
      const limit = Math.max(target.clientWidth, target.clientHeight, 1);
      // The finger moves the picture with it: a positive dx is a negative Pan X,
      // which is `ReliefRenderer.panBy`'s own sign.
      const wasX = settings.panX;
      const wasY = settings.panY;
      settings.panX = Math.max(-limit, Math.min(limit, settings.panX - dx));
      settings.panY = Math.max(-limit, Math.min(limit, settings.panY - dy));
      // A drag against a stop moved nothing, and a release that moved nothing
      // writes nothing — the app's `framingMoved` rule.
      if (settings.panX !== wasX || settings.panY !== wasY) framingTouched = true;
      view.setPan(settings.panX, settings.panY);
      pushFraming();
      syncCrosshair();
    };

    const onDown = (event: PointerEvent): void => {
      const p = local(event);
      pointers.set(event.pointerId, { x: p.x, y: p.y });
      try {
        target.setPointerCapture(event.pointerId);
      } catch {
        // A synthetic pointer cannot be captured; the move events still arrive.
      }
      if (pointers.size === 1) {
        downX = p.x;
        downY = p.y;
        downAt = event.timeStamp;
        moved = false;
      } else if (pointers.size === 2) {
        moved = true;
        pinchStartDist = distance();
        pinchStartPanZ = settings.panZ;
        const mid = midpoint();
        lastMidX = mid.x;
        lastMidY = mid.y;
      }
    };

    const onMove = (event: PointerEvent): void => {
      const known = pointers.get(event.pointerId);
      if (!known) return;
      const p = local(event);
      pointers.set(event.pointerId, { x: p.x, y: p.y });

      if (pointers.size >= 2) {
        const mid = midpoint();
        panBy(mid.x - lastMidX, mid.y - lastMidY);
        lastMidX = mid.x;
        lastMidY = mid.y;
        const now = distance();
        if (pinchStartDist > 1 && now > 1) {
          const next = Math.max(PAN_Z_MIN, Math.min(PAN_Z_MAX, pinchStartPanZ * (pinchStartDist / now)));
          if (next !== settings.panZ) {
            settings.panZ = next;
            framingTouched = true;
            view.setPanZ(next);
            pushFraming();
            syncCrosshair();
          }
        }
        return;
      }

      if (!moved) {
        if (Math.hypot(p.x - downX, p.y - downY) <= SLOP) return;
        moved = true;
      }
      // One-finger drag = manual tilt, mirroring Android: `renderer.setTilt(
      // clamp(x/width*2-1), clamp(y/height*2-1))` is an ABSOLUTE position, not a
      // delta, and it only runs without a live sensor -- with the gyro on, tilt
      // comes from the device and a drag would fight it. Pan belongs to two
      // fingers, as the user asked.
      if (!tiltLive) {
        const rect = target.getBoundingClientRect();
        if (rect.width > 0 && rect.height > 0) {
          const tx = Math.max(-1, Math.min(1, (p.x / rect.width) * 2 - 1));
          const ty = Math.max(-1, Math.min(1, (p.y / rect.height) * 2 - 1));
          view.setTilt(tx, ty);
          syncCrosshair();
        }
      }
    };

    const finish = (event: PointerEvent, cancelled: boolean): void => {
      const wasLast = pointers.size === 1;
      const held = event.timeStamp - downAt;
      pointers.delete(event.pointerId);
      if (target.hasPointerCapture(event.pointerId)) target.releasePointerCapture(event.pointerId);
      if (pointers.size === 1) {
        const mid = midpoint();
        lastMidX = mid.x;
        lastMidY = mid.y;
        pinchStartDist = 0;
      }
      if (!cancelled && wasLast && !moved && held < 320) {
        const rect = target.getBoundingClientRect();
        if (rect.width > 0 && rect.height > 0) {
          const ndcX = ((event.clientX - rect.left) / rect.width) * 2 - 1;
          const ndcY = -(((event.clientY - rect.top) / rect.height) * 2 - 1);
          const origin = view.tapOrigin(ndcX, ndcY);
          if (origin) {
            if (origin.x !== settings.originX || origin.y !== settings.originY) {
              framingTouched = true;
            }
            settings.originX = origin.x;
            settings.originY = origin.y;
            pushFraming();
            syncCrosshair();
          }
        }
      }
      if (pointers.size === 0) {
        moved = false;
        pinchStartDist = 0;
        // A gesture owns the renderer's values for its span and the index is told
        // once, at the end — and a gesture that moved nothing writes nothing.
        if (framingTouched) {
          framingTouched = false;
          persist();
        }
      }
    };

    const onUp = (event: PointerEvent): void => finish(event, false);
    const onCancel = (event: PointerEvent): void => finish(event, true);

    target.addEventListener('pointerdown', onDown);
    target.addEventListener('pointermove', onMove);
    target.addEventListener('pointerup', onUp);
    target.addEventListener('pointercancel', onCancel);
    teardownList.push(() => {
      target.removeEventListener('pointerdown', onDown);
      target.removeEventListener('pointermove', onMove);
      target.removeEventListener('pointerup', onUp);
      target.removeEventListener('pointercancel', onCancel);
    });
  }

